#!/usr/bin/env node
// Build src/data/local_data/boston/city-outline.json from the bundled Boston neighborhood
// areas. The scanner preset only needs "how far is this point from the city",
// so every neighborhood's outer ring is simplified (Douglas-Peucker, ~30 m)
// and kept as-is: interior shared edges never change a distance measured from
// outside the city, and a point inside any ring is inside Boston.
//
//   node scripts/build-boston-outline.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const SOURCE = `${root}src/data/local_data/boston/neighborhoods.geojsonl`;
const OUTPUT = `${root}src/data/local_data/boston/city-outline.json`;
const TOLERANCE_DEG = 0.0003;

function perpendicularDistance(p, a, b) {
  const dx = b[0] - a[0];
  const dy = b[1] - a[1];
  const length2 = dx * dx + dy * dy;
  if (!length2) return Math.hypot(p[0] - a[0], p[1] - a[1]);
  const t = Math.max(
    0,
    Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / length2),
  );
  return Math.hypot(p[0] - (a[0] + t * dx), p[1] - (a[1] + t * dy));
}

function simplify(points, tolerance) {
  if (points.length < 3) return points;
  let maxDistance = 0;
  let index = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const d = perpendicularDistance(points[i], points[0], points.at(-1));
    if (d > maxDistance) {
      maxDistance = d;
      index = i;
    }
  }
  if (maxDistance <= tolerance) return [points[0], points.at(-1)];
  const left = simplify(points.slice(0, index + 1), tolerance);
  const right = simplify(points.slice(index), tolerance);
  return [...left.slice(0, -1), ...right];
}

const rings = [];
for (const line of readFileSync(SOURCE, 'utf8').split('\n')) {
  if (!line.trim()) continue;
  const { geometry } = JSON.parse(line);
  const polygons =
    geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates;
  for (const polygon of polygons) {
    const ring = simplify(polygon[0], TOLERANCE_DEG).map(([lon, lat]) => [
      Number(lon.toFixed(5)),
      Number(lat.toFixed(5)),
    ]);
    if (ring.length >= 4) rings.push(ring);
  }
}

const vertices = rings.reduce((sum, ring) => sum + ring.length, 0);
writeFileSync(
  OUTPUT,
  `${JSON.stringify({
    source:
      'Generated by scripts/build-boston-outline.mjs from neighborhoods.geojsonl; do not edit by hand.',
    format: '[lon, lat] simplified neighborhood outer rings',
    rings,
  })}\n`,
);
console.log(`wrote ${OUTPUT}: ${rings.length} rings, ${vertices} vertices`);
